def lang_index(lang: str) -> int:
    return 1 if lang == "ar" else 0


def t(key: str, lang: str = DEFAULT_LANG, **values: Any) -> str:
    pair = STRINGS.get(key)
    text = pair[lang_index(lang)] if pair else key
    return text.format(**values) if values else text


def strings_for(lang: str) -> dict[str, str]:
    i = lang_index(lang)
    return {k: v[i] for k, v in STRINGS.items()}


def region_labels(lang: str, regions: list[str]) -> dict[str, str]:
    return {r: (REGION_LABELS.get(r, r) if lang == "ar" else r) for r in regions}


def localize(message: str, lang: str) -> str:
    """Translate a server message (written in Hebrew in the code) to the user's language."""
    if lang != "ar" or not isinstance(message, str):
        return message
    if message in MESSAGES_AR:
        return MESSAGES_AR[message]
    for pattern, template in PATTERNS_AR:
        m = pattern.match(message)
        if m:
            return template.format(*m.groups())
    return message


def get_lang(request: Request) -> str:
    """?lang= (explicit) > cookie > the browser's preferred language > Hebrew."""
    q = request.query_params.get("lang")
    if q in LANGS:
        return q
    c = request.cookies.get(COOKIE)
    if c in LANGS:
        return c
    for part in request.headers.get("accept-language", "").split(","):
        code = part.split(";")[0].strip().lower()[:2]
        if code in LANGS:
            return code
        if code in ("en", "ru", "fr"):  # a non-Hebrew, non-Arabic browser: stay with the default
            break
    return DEFAULT_LANG
